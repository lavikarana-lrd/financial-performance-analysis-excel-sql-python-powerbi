# 7. For each Business Unit, what is the ratio of Total Actual Revenue generated to the Total 'Cost_to_company' of all active employees?
select r.Business_unit, r.revenue, h.total_CTC, round(r.revenue/h.total_CTC) as revenue_to_CTC from 
(select Business_unit, round(sum(Amount),2) as Revenue from financial_transactions where Account_type='Revenue'
 group by business_unit) r join (select business_unit, sum(cost_to_company) as total_CTC from headcount
 where status ='Active' group by business_unit)h on r.business_unit = h.business_unit;


# 9. Calculate the total revenue generated by each customer. Then, use a window function to 
# rank the top 3 highest-revenue customers within each customer segment (Retail, Enterprise, Online) 
WITH Customer_Revenue AS (
SELECT c.Customer_id, c.Customer_name, c.segment, SUM(f.Amount) AS Total_Revenue
FROM Customers c JOIN Financial_Transactions f ON c.Customer_id = f.Customer_id
WHERE f.Account_type = 'Revenue'GROUP BY c.Customer_id, c.Customer_name, c.segment),
Ranked_Customers AS (
SELECT Customer_id, Customer_name, segment, Total_Revenue,
RANK() OVER (PARTITION BY segment ORDER BY Total_Revenue DESC) as Revenue_Rank
FROM Customer_Revenue)
SELECT Customer_id, Customer_name, segment, Total_Revenue, Revenue_Rank
FROM Ranked_Customers WHERE Revenue_Rank <= 3
ORDER BY segment ASC, Revenue_Rank ASC;

