with customer_revenue as(
select c.customer_id, c.customer_name, sum(f.amount) as total_revenue from financial_transactions f
join customers c on f.customer_id = c.customer_id where f.account_type = 'Revenue' group by
c.customer_id, c.customer_name),
Ranked_revenue as (select customer_id, customer_name, total_revenue, sum(total_revenue) over 
(order by total_revenue desc) as cumulative_revenue, sum(total_revenue) over () as grand_total_revenue
from customer_revenue)
SELECT Customer_name, Customer_id, Total_Revenue, Cumulative_Revenue,
ROUND((Cumulative_Revenue / Grand_Total_Revenue) * 100, 2) AS Cumulative_Percentage
FROM Ranked_Revenue ORDER BY Total_Revenue DESC;
